
CREATE DATABASE IF NOT EXISTS sistema_cores;

USE sistema_cores;

CREATE TABLE IF NOT EXISTS cor (
id INT AUTO_INCREMENT PRIMARY KEY,
nome VARCHAR(50) NOT NULL,
familia VARCHAR(50) NOT NULL,
codigo_hex VARCHAR(7) NOT NULL UNIQUE,
tipo VARCHAR(20) NOT NULL);

CREATE TABLE IF NOT EXISTS cor_especial (
cor_id INT PRIMARY KEY,
metalica BOOLEAN NOT NULL,
acabamento VARCHAR(50) NOT NULL,
FOREIGN KEY (cor_id)
REFERENCES cor(id)
ON DELETE CASCADE);
